const lerpHex = (a: number, b: number, t: number) =>
  Math.round(a + (b - a) * t)
    .toString(16)
    .padStart(2, '0')
const grad = (t: number) =>
  `#${lerpHex(0x0e, 0x8b, t)}${lerpHex(0xa5, 0x5c, t)}${lerpHex(0xe9, 0xf6, t)}`

